const express = require('express');
const router = express.Router();

// ─── Platform-domain detection ────────────────────────────────────────────────
// Mirrors the same logic used by isPlatformHost() in index.js and
// isPlatformDomain() in client/src/utils/storeRouting.js.
// A request is considered "platform" when the Host/X-Forwarded-Host header
// belongs to onedash.cloud / bluetick.cloud / localhost / IP / PaaS domains.
// Everything else is treated as a merchant custom-domain request.

const _platformDomain = (process.env.PLATFORM_DOMAIN || '')
    .toLowerCase().replace(/^https?:\/\//, '').replace(/\/+$/, '');

const _extraPlatformDomains = (process.env.EXTRA_PLATFORM_DOMAINS || '')
    .split(',')
    .map(d => d.trim().toLowerCase().replace(/^https?:\/\//, '').replace(/\/.*$/, ''))
    .filter(Boolean);

const PAAS_PATTERNS = [
    'sslip.io', 'nip.io', 'traefik.me',
    'ngrok.io', 'ngrok-free.app',
    'railway.app', 'onrender.com', 'vercel.app', 'netlify.app',
    'workers.dev', // Cloudflare worker preview URLs
];

function isPlatformHost(hostname) {
    if (!hostname) return true;
    const h = hostname.toLowerCase().split(':')[0]; // strip port if present
    if (h === 'localhost' || h === '127.0.0.1') return true;
    if (/^(\d{1,3}\.){3}\d{1,3}$/.test(h)) return true;             // raw IP
    if (PAAS_PATTERNS.some(p => h.includes(p))) return true;         // PaaS/dev tunnel
    if (_platformDomain && (h === _platformDomain || h.endsWith(`.${_platformDomain}`))) return true;
    if (_extraPlatformDomains.some(d => h === d || h.endsWith(`.${d}`))) return true;
    // Built-in dual-domain safety net (onedash.cloud + legacy bluetick.cloud)
    if (h === 'onedash.cloud'  || h.endsWith('.onedash.cloud'))  return true;
    if (h === 'bluetick.cloud' || h.endsWith('.bluetick.cloud')) return true;
    return false;
}

// @route   GET /robots.txt
// @desc    Serve the correct robots.txt based on the requesting domain:
//          - Platform domain (onedash.cloud) → SaaS platform rules
//          - Merchant custom domain (www.amardryfruits.in) → Store-only rules
router.get('/', async (req, res) => {
    // Cloudflare Worker preserves the original domain in X-Forwarded-Host.
    // On direct server access (staging/dev), fall back to the Host header.
    const requestHost = (
        req.headers['x-forwarded-host'] || req.get('host') || ''
    ).toLowerCase().split(':')[0];

    res.type('text/plain; charset=utf-8');

    // ── CASE 1: Merchant Custom-Domain ──────────────────────────────────────
    if (!isPlatformHost(requestHost) && requestHost) {
        // The sitemap URL is built from the exact domain Googlebot used to
        // reach us — this ensures the Sitemap directive always points to the
        // correct domain, never to onedash.cloud.
        const proto = req.headers['x-forwarded-proto'] || 'https';
        const storeOrigin = `${proto}://${requestHost}`;

        res.setHeader('Cache-Control', 'public, max-age=3600'); // 1 h — refreshes quickly if domain changes

        return res.send([
            `# robots.txt for ${requestHost}`,
            `# Auto-generated by OneDash — do not edit manually`,
            ``,
            `User-agent: *`,
            `Allow: /`,
            ``,
            `# Disallow private customer-account and order pages`,
            `Disallow: /account/`,
            `Disallow: /verify`,
            `Disallow: /order-success`,
            ``,
            `# Sitemap — Googlebot fetches this automatically; merchant submits once to GSC`,
            `Sitemap: ${storeOrigin}/sitemap.xml`,
        ].join('\n'));
    }

    // ── CASE 2: OneDash Platform Domain ─────────────────────────────────────
    try {
        // Priority order for the canonical URL used in the Sitemap directive:
        // 1. Admin-configured canonical URL in Superadmin → SEO settings (DB)
        // 2. PLATFORM_DOMAIN env var
        // 3. FRONTEND_URL env var
        // 4. The actual incoming request host (last-resort fallback)
        let canonicalUrl = '';
        let robotsSetting = 'index, follow';

        try {
            const LandingPage = require('../models/LandingPage');
            const landing = await LandingPage.findOne({ attributes: ['seo'] });
            if (landing?.seo?.canonicalUrl && !landing.seo.canonicalUrl.includes('localhost')) {
                canonicalUrl = landing.seo.canonicalUrl.trim().replace(/\/+$/, '');
                if (!canonicalUrl.startsWith('http')) canonicalUrl = `https://${canonicalUrl}`;
            }
            if (landing?.seo?.robots) {
                robotsSetting = landing.seo.robots;
            }
        } catch (_) { /* Non-fatal — proceed with env-var fallbacks */ }

        if (!canonicalUrl && _platformDomain) {
            canonicalUrl = `https://${_platformDomain}`;
        }

        if (!canonicalUrl && process.env.FRONTEND_URL && !process.env.FRONTEND_URL.includes('localhost')) {
            canonicalUrl = process.env.FRONTEND_URL.replace(/\/+$/, '');
        }

        if (!canonicalUrl) {
            // Absolute last-resort: derive from the actual incoming request
            const proto = req.headers['x-forwarded-proto'] || req.protocol || 'https';
            canonicalUrl = `${proto}://${requestHost}`;
        }

        const isNoIndex = robotsSetting.toLowerCase().includes('noindex');

        res.setHeader('Cache-Control', 'public, max-age=86400'); // 24 h for platform

        let content = [
            `# robots.txt for ${canonicalUrl}`,
            `# Auto-generated by OneDash`,
            ``,
            `User-agent: *`,
        ];

        if (isNoIndex) {
            content.push(`Disallow: /`);
        } else {
            content.push(
                `Allow: /`,
                ``,
                `# Disallow private SaaS app pages — not meant for public search indexing`,
                `Disallow: /api/`,
                `Disallow: /admin/`,
                `Disallow: /superadmin/`,
                `Disallow: /dashboard`,
                `Disallow: /checkout`,
                `Disallow: /settings`,
                `Disallow: /contacts`,
                `Disallow: /campaigns`,
                `Disallow: /templates`,
                `Disallow: /inbox`,
            );
        }

        content.push(
            ``,
            `# Sitemap`,
            `Sitemap: ${canonicalUrl}/sitemap.xml`,
        );

        return res.send(content.join('\n'));

    } catch (err) {
        console.error('[Robots] Error serving robots.txt:', err);
        // Safe hardcoded fallback — never crashes
        const fallbackDomain = process.env.PLATFORM_DOMAIN || 'onedash.cloud';
        res.setHeader('Cache-Control', 'public, max-age=300');
        return res.send([
            `User-agent: *`,
            `Allow: /`,
            `Disallow: /api/`,
            `Disallow: /admin/`,
            ``,
            `Sitemap: https://${fallbackDomain}/sitemap.xml`,
        ].join('\n'));
    }
});

module.exports = router;
